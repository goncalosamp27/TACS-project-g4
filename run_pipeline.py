"""Run the TACS T1 -> T2 -> T3 -> Aer validation for one or all instances.

From the root of the TACS project:
    python run_pipeline.py --instance small
    python run_pipeline.py --instance all

Uses the active Python interpreter (ideally project/.venv/bin/python).
It does not edit generated Qiskit code; full simulation output is archived
under transformations/generated/results/, and only the useful summary is shown.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
TRANSFORMATIONS = ROOT / "transformations"
GENERATED = TRANSFORMATIONS / "generated"
RESULTS = GENERATED / "results"


def choose_script(explicit: str | None, names: tuple[str, ...]) -> Path:
    if explicit:
        candidate = Path(explicit).expanduser()
        if not candidate.is_absolute():
            candidate = ROOT / candidate
        if not candidate.is_file():
            raise FileNotFoundError(f"Cannot find transformation script: {candidate}")
        return candidate
    for name in names:
        candidate = TRANSFORMATIONS / name
        if candidate.is_file():
            return candidate
    raise FileNotFoundError(
        f"Could not find any of {names} in {TRANSFORMATIONS}. "
        "Provide the file explicitly using --t2-script or --t3-script."
    )


def run(command: list[str], *, show: bool = True) -> str:
    print("$", " ".join(command), flush=True)
    process = subprocess.run(
        command, cwd=ROOT, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT, check=False,
    )
    if process.returncode != 0:
        print(process.stdout[-12000:], file=sys.stderr)
        raise RuntimeError(f"Step failed (exit code {process.returncode}): {command[1]}")
    if show:
        print(process.stdout.rstrip())
    return process.stdout


def run_instance(instance: str, args: argparse.Namespace, t2: Path, t3: Path) -> None:
    problem = ROOT / "code" / "object" / f"{instance}_problem_DSL_object_diagram.py"
    if not problem.is_file():
        raise FileNotFoundError(f"Problem ObjectModel not found: {problem}")
    print(f"\n{'=' * 65}\nINSTANCE: {instance.upper()}\n{'=' * 65}", flush=True)

    t1_output = run([sys.executable, str(TRANSFORMATIONS / "t1_problem_to_qubo.py"), str(problem)])
    generated_matches = re.findall(r"^Generated:\s*(.+?)\s*$", t1_output, flags=re.MULTILINE)
    if not generated_matches:
        raise ValueError("T1 output did not report its generated QUBO file")
    qubo = Path(generated_matches[-1])
    if not qubo.is_absolute():
        qubo = ROOT / qubo
    if not qubo.is_file():
        raise FileNotFoundError(f"T1 reported a QUBO that does not exist: {qubo}")

    t2_command = [sys.executable, str(t2), "--qubo-file", str(qubo),
                  "--config", str(args.config)]
    if args.depth is not None:
        t2_command += ["--depth", str(args.depth)]
    if args.cost_scale is not None:
        t2_command += ["--cost-scale", args.cost_scale]
    if args.gammas is not None:
        t2_command += ["--gammas", *[str(x) for x in args.gammas]]
    if args.betas is not None:
        t2_command += ["--betas", *[str(x) for x in args.betas]]
    run(t2_command)
    t3_command = [sys.executable, str(t3), "--config", str(args.config)]
    if args.shots is not None:
        t3_command += ["--shots", str(args.shots)]
    run(t3_command)

    script = GENERATED / "qiskit_circuit.py"
    if not script.is_file():
        raise FileNotFoundError(f"No Qiskit program generated by T3: {script}")
    output = run([sys.executable, str(script)], show=False)
    RESULTS.mkdir(parents=True, exist_ok=True)
    log_path = RESULTS / f"{instance}.log"
    log_path.write_text(output, encoding="utf-8")
    marker = "=== Classical baseline (exact brute force) ==="
    if marker not in output:
        print(f"Simulator finished, but validation section was not found. Full log: {log_path}")
    else:
        print("\n" + marker + output.split(marker, 1)[1].rstrip())
    print(f"\nFull circuit, counts and validation log: {log_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", choices=("small", "medium", "large", "all"), default="small")
    parser.add_argument("--config", type=Path,
                        default=TRANSFORMATIONS / "solver_config.json",
                        help="JSON solver configuration (default: transformations/solver_config.json)")
    parser.add_argument("--depth", type=int, help="Override QAOA depth from JSON")
    parser.add_argument("--gammas", nargs="+", type=float, help="One gamma per layer")
    parser.add_argument("--betas", nargs="+", type=float, help="One beta per layer")
    parser.add_argument("--cost-scale", choices=("max_abs", "none"),
                        help="Override cost scale from JSON")
    parser.add_argument("--shots", type=int, help="Override shot count from JSON")
    parser.add_argument("--t2-script", help="Path to corrected T2 if its filename differs")
    parser.add_argument("--t3-script", help="Path to corrected T3 if its filename differs")
    args = parser.parse_args()
    if args.depth is not None and args.depth < 1:
        parser.error("--depth must be >= 1")
    if args.shots is not None and args.shots < 1:
        parser.error("--shots must be >= 1")
    if args.depth is not None and args.gammas is not None and len(args.gammas) != args.depth:
        parser.error("--gammas must contain exactly --depth values")
    if args.depth is not None and args.betas is not None and len(args.betas) != args.depth:
        parser.error("--betas must contain exactly --depth values")
    args.config = args.config.expanduser().resolve()
    if not args.config.is_file():
        parser.error(f"Solver configuration not found: {args.config}")

    t2 = choose_script(args.t2_script, (
        "t2_solution_to_quantum.py",
    ))
    t3 = choose_script(args.t3_script, (
        "t3_quantum_to_qiskit.py",
    ))
    print(f"T2: {t2.name} | T3: {t3.name} | Python: {sys.executable}")
    cases = ("small", "medium", "large") if args.instance == "all" else (args.instance,)
    for case in cases:
        run_instance(case, args, t2, t3)
    print("\nAll requested instances completed.")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, FileNotFoundError, ValueError) as error:
        sys.exit(f"\nERROR: {error}")
